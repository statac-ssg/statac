#[test]
fn the_present_minute_carries_its_offset_only_where_the_clocks_show_it_twice() {
    let zone = TimeZone::get("Europe/London").unwrap();
    let at = |moment: &str| {
        let moment: jiff::Timestamp = moment.parse().unwrap();
        moment.to_zoned(zone.clone())
    };
    // Summer and winter, each time shown once.
    assert_eq!(
        minute_of(&at("2026-07-01T08:15:59Z"), true),
        date("2026-07-01 09:15")
    );
    assert_eq!(
        minute_of(&at("2026-12-31T23:59:00Z"), true),
        date("2026-12-31 23:59")
    );
    // The clocks go back at 02:00 on 25 October 2026, and show 01:30
    // twice: a time written without an offset is read as the first.
    let (first, second) = (at("2026-10-25T00:30:00Z"), at("2026-10-25T01:30:00Z"));
    assert_eq!(minute_of(&first, true), date("2026-10-25 01:30"));
    assert_eq!(minute_of(&second, true), date("2026-10-25 01:30 +00:00"));
    // A site naming no zone reads every time as written.
    assert_eq!(minute_of(&second, false), date("2026-10-25 01:30"));

    let (dates, _, _) = site("timezone: Europe/London\n");
    let moment = |zoned: &jiff::Zoned| dates.instant(&minute_of(zoned, true));
    assert_eq!(moment(&first), first.timestamp().as_second());
    assert_eq!(moment(&second), second.timestamp().as_second());
}

#[test]
fn a_stamp_written_as_the_clocks_change_names_the_day_and_time_asked_for() {
    use crate::stamp::{Moment, read};
    let (dates, _, _) = site("timezone: Europe/London\n");
    let on = |today: &str| Moment {
        today: date(today),
        now: date(&format!("{today} 00:00")),
    };
    let written = |stamp: &str, today: &str| {
        let stamp = read(stamp).unwrap().unwrap();
        stamp.written(&on(today)).unwrap()
    };
    // The clocks go forward on Sunday 29 March 2026 and back on Sunday
    // 25 October: each day is the next on the calendar all the same.
    assert_eq!(written("=tomorrow", "2026-03-28"), "2026-03-29");
    assert_eq!(written("=tomorrow", "2026-03-29"), "2026-03-30");
    assert_eq!(written("=sunday 09:00", "2026-03-28"), "2026-03-29 09:00");
    assert_eq!(written("=yesterday", "2026-10-26"), "2026-10-25");
    assert_eq!(written("=monday", "2026-10-25"), "2026-10-26");
    let hours = |earlier: &str, later: &str| {
        (dates.instant(&date(later)) - dates.instant(&date(earlier))) / 3_600
    };
    // A day the clocks change in is an hour short or an hour long.
    let day = written("=today", "2026-03-29");
    assert_eq!(hours(&day, &written("=tomorrow", "2026-03-29")), 23);
    let day = written("=today", "2026-10-25");
    assert_eq!(hours(&day, &written("=tomorrow", "2026-10-25")), 25);
    // A time the clocks skip is read as the moment after the change.
    let skipped = written("=today 01:30", "2026-03-29");
    assert_eq!(skipped, "2026-03-29 01:30");
    assert_eq!(dates.moment(&date(&skipped)), "2026-03-29T02:30:00+01:00");
    // A time before the change and one after it are read either side.
    let morning = written("=sunday 00:30", "2026-10-24");
    let evening = written("=sunday 18:30", "2026-10-24");
    assert_eq!(dates.moment(&date(&morning)), "2026-10-25T00:30:00+01:00");
    assert_eq!(dates.moment(&date(&evening)), "2026-10-25T18:30:00+00:00");
}

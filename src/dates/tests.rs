#[test]
fn the_formats_sites_write_give_every_date_as_before() {
    for case in CASES {
        let mut settings = format!("language: {}\ntimezone: {}\n", case.language, case.zone);
        if let Some(format) = case.format {
            settings.push_str(&format!("date_format: \"{format}\"\n"));
        }
        let (dates, problems, _) = site(&settings);
        assert!(problems.is_empty(), "{settings}{problems:?}");
        for (written, shown, moment, rss, examples) in case.rows {
            let at = date(written);
            let label = format!("{} {} {written}", case.language, case.zone);
            assert_eq!(dates.format(main(), &at, None).unwrap(), *shown, "{label}");
            assert_eq!(dates.moment(&at), *moment, "{label}");
            assert_eq!(dates.moment_rss(&at), *rss, "{label}");
            for (example, expected) in case.examples.iter().zip(*examples) {
                let written = dates.format(main(), &at, Some(example));
                assert_eq!(written.as_deref(), Ok(*expected), "{label} {example}");
            }
        }
    }
}

fn words(words: Words) -> DateWords {
    DateWords {
        words: Arc::new(words),
        from: WordsFrom::Site("languages/xx.yaml".into()),
        zeros: true,
    }
}

fn english() -> DateWords {
    DateWords::english()
}

fn list<const N: usize>(words: &str) -> Option<[String; N]> {
    let words: Vec<String> = words.split(", ").map(String::from).collect();
    Some(words.try_into().expect("as many words as the list holds"))
}

fn bundled(tag: &str) -> Words {
    (*crate::language::bundled(tag).unwrap().1).clone()
}


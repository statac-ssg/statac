#[test]
fn dates_are_ordered_by_the_moments_they_name() {
    let (dates, ..) = site("timezone: Europe/London\n");
    let summer = date("2026-07-04T21:40");
    let east = date("2026-07-04T22:00+02:00");
    let utc = date("2026-07-04T20:40Z");
    let day = date("2026-07-04");
    assert_eq!(dates.order(&east, &summer), Ordering::Less);
    assert_eq!(dates.order(&utc, &summer), Ordering::Equal);
    assert_eq!(dates.order(&day, &east), Ordering::Less);
    assert_eq!(dates.newest(&[&east, &summer, &day]), Some(&summer));
    assert!(std::ptr::eq(dates.newest(&[&summer, &utc]).unwrap(), &utc));
    assert_eq!(dates.newest(&[]), None);
}


fn site(settings: &str) -> (Dates, Vec<Problem>, Sources) {
    let site = TempSite::new(&[("statac.yaml", settings)]);
    let mut sources = Sources::default();
    let (settings, mut problems) = crate::config::read(&site.root, &mut sources);
    let (dates, found) = Dates::read(&site.root, &settings, &mut sources);
    problems.extend(found);
    (dates, problems, sources)
}

fn date(text: &str) -> Date {
    crate::date::read(text).unwrap_or_else(|fault| panic!("{text}: {fault:?}"))
}

/// The site's main language, the first it declares.
fn main() -> LanguageId {
    LanguageId::from_index(0)
}


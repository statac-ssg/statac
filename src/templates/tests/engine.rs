fn check(cases: &[Case]) {
    for case in cases {
        let (kind, line, at) = told(case.layout);
        assert_eq!(
            crate::wording::headline(&kind),
            case.headline,
            "{}",
            case.layout
        );
        assert_eq!(
            crate::wording::suggestion(&kind).as_deref(),
            case.suggestion,
            "{}",
            case.layout
        );
        assert_eq!((line, at.as_str()), (case.line, case.at), "{}", case.layout);
    }
}

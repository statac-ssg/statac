//! What the template engine stops at, told in Statac's own words: each
//! case read and built by the engine itself, so a change to the engine's
//! words fails here.

use super::*;

/// A layout, the problem it comes to as printed, its suggestion, and the
/// line and text it is placed at.
struct Case {
    layout: &'static str,
    headline: &'static str,
    suggestion: Option<&'static str>,
    line: usize,
    at: &'static str,
}

const fn case(
    layout: &'static str,
    headline: &'static str,
    suggestion: Option<&'static str>,
    line: usize,
    at: &'static str,
) -> Case {
    Case {
        layout,
        headline,
        suggestion,
        line,
        at,
    }
}

/// The problem a post built with `layout` comes to, read or built.
fn told(layout: &str) -> (Kind, usize, String) {
    let built = site(&[
        NO_HOME,
        (
            "content/post-1.md",
            "---\ntitle: Post 1\ndate: 2026-10-01\n---\nSome writing.\n",
        ),
        ("templates/base.html", "{% block main %}{% endblock %}"),
        ("templates/ring.html", "{% extends \"page\" %}"),
        ("templates/page.html", layout),
    ]);
    let mut problems = built.problems.clone();
    problems.extend(built.render("post-1.md").problems);
    let shown = [
        "malformed-template",
        "template-stopped",
        "no-value",
        "unknown-word",
    ];
    let problem = problems
        .into_iter()
        .find(|p| shown.contains(&p.kind.name()))
        .unwrap_or_else(|| panic!("{layout}: nothing told"));
    let place = problem.place.expect("placed");
    let sources = built.renderer.sources();
    let line = sources.line_number(place.source, place.span.range().start);
    (problem.kind, line, sources.spelling(place).to_owned())
}

